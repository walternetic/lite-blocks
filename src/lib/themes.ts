export const DEFAULT_THEME_ID = 'notion-minimal';

export function getThemeById(themeId?: string): ThemeDefinition {
  if (!themeId) return THEMES[0];
  const found = THEMES.find((t) => t.id === themeId);
  return found || THEMES[0];
}

export function getThemeCssVariables(theme: ThemeDefinition): Record<string, string> {
  return {
    '--theme-bg-app': theme.colors.bgApp,
    '--theme-bg-sidebar': theme.colors.bgSidebar,
    '--theme-bg-surface': theme.colors.bgSurface,
    '--theme-bg-hover': theme.colors.bgHover,
    '--theme-border': theme.colors.border,
    '--theme-text-main': theme.colors.textMain,
    '--theme-text-muted': theme.colors.textMuted,
    '--theme-accent': theme.colors.accent,
    '--theme-accent-hover': theme.colors.accentHover,
    '--theme-accent-text': theme.colors.accentText,
    '--theme-code-bg': theme.colors.codeBg,
    '--theme-callout-bg': theme.colors.calloutBg,
  };
}
